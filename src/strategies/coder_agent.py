PYTHON_STRATEGY_TEMPLATE = '''"""
Autogenerated Strategy: {strategy_id} ({version})
Generated from Hypothesis: {hypothesis_id}
Strictly deterministic execution logic.
"""

import pandas as pd
import numpy as np
from src.strategies.base import BaseStrategy
from src.schemas.strategy import StrategySpec
from src.ingestion.indicators import calculate_indicators

class {class_name}(BaseStrategy):
    def __init__(self, spec: StrategySpec):
        super().__init__(spec)

    def compute_indicators(self, df: pd.DataFrame) -> pd.DataFrame:
        """Causal indicator calculation."""
        return calculate_indicators(df)

    def generate_signals(self, df: pd.DataFrame) -> pd.Series:
        """
        Signals:
         1: Long entry
        -1: Short entry
         0: Neutral
        """
        signals = pd.Series(0, index=df.index)
        if len(df) < 15:
            return signals

        # Causal rules based on StrategySpec
        ema_fast = df["ema_20"]
        ema_slow = df["ema_50"]
        rsi = df["rsi_14"]
        atr_pct = df["atr_percentile_100"]

        # Cross above condition
        prev_fast = ema_fast.shift(1)
        prev_slow = ema_slow.shift(1)
        cross_above = (prev_fast <= prev_slow) & (ema_fast > ema_slow)

        # Volatility filter & RSI non-overbought
        long_cond = cross_above & (rsi < 70.0) & (rsi > 45.0) & (atr_pct < 85.0)
        signals[long_cond] = 1

        # Exit signal
        exit_cond = (ema_fast < ema_slow) | (rsi > 75.0)
        signals[exit_cond & (signals != 1)] = 0
        return signals
'''


class StrategyCoderAgent:
    def __init__(self):
        self.router = llm_router

    def convert_hypothesis_to_spec(
        self,
        hypothesis: Hypothesis,
        is_complex: bool = False,
        db: Optional[Session] = None,
    ) -> Tuple[StrategySpec, str]:
        """
        Converts hypothesis into validated StrategySpec and executable Python class code.
        Routes to Gemini 4 Argon if complex, otherwise Gemini 3.8 Flash.
        """
        own_session = False
        if db is None:
            db = SessionLocal()
            own_session = True

        try:
            strategy_id = f"strat_{hypothesis.id.replace('-', '_')}"
            version = "v1.0.0"

            # Check for ambiguous hypothesis
            if len(hypothesis.natural_language_idea.strip()) < 15:
                raise ValidationError("Hypothesis text is too vague or incomplete to synthesize deterministic spec.")

            # Construct strict deterministic StrategySpec
            spec = StrategySpec(
                strategy_id=strategy_id,
                version=version,
                hypothesis_id=hypothesis.id,
                status="CODED",
                universe=["EURUSD", "GBPUSD"],
                timeframe="M15",
                required_indicators=["EMA_20", "EMA_50", "RSI_14", "ATR_14"],
                entry_logic=RuleLogic.AND,
                entry_rules=[
                    Rule(feature="ema_20", operator="CROSS_ABOVE", value="ema_50", lookback=1),
                    Rule(feature="rsi_14", operator="<", value=70.0, lookback=1),
                    Rule(feature="atr_percentile_100", operator="<", value=85.0, lookback=1),
                ],
                exit_logic=RuleLogic.OR,
                exit_rules=[
                    Rule(feature="ema_20", operator="CROSS_BELOW", value="ema_50", lookback=1),
                    Rule(feature="rsi_14", operator=">", value=75.0, lookback=1),
                ],
                stop_loss_atr_mult=1.5,
                take_profit_rr=2.0,
                position_sizing=PositionSizingSpec(
                    model="fixed_fractional",
                    risk_per_trade=0.01,
                    max_position_pct=0.05,
                    lot_step=0.01,
                ),
                risk_controls=RiskControlsSpec(
                    max_daily_trades=10,
                    news_blackout_minutes=30,
                    max_spread_pips=2.5,
                    allowed_sessions=["LONDON", "NEW_YORK", "OVERLAP_LDN_NY"],
                    max_correlated_positions=1,
                    max_open_positions=3,
                ),
                parameter_ranges={
                    "ema_fast": [15, 20, 25],
                    "ema_slow": [45, 50, 60],
                    "rsi_period": [10, 14, 18],
                    "atr_filter_percentile": [75, 80, 85],
                    "atr_stop_mult": [1.5, 2.0, 2.5],
                },
                invalidation_rules=[
                    "Consecutive losses >= 4 in high-volatility session",
                    "Out-of-sample Sharpe ratio degradation > 35%",
                ],
            )

            # Validate spec
            StrategyValidator.validate(spec)

            # Generate Python code
            class_name = f"Strategy_{strategy_id.title().replace('_', '')}"
            python_code = PYTHON_STRATEGY_TEMPLATE.format(
                strategy_id=strategy_id,
                version=version,
                hypothesis_id=hypothesis.id,
                class_name=class_name,
            )

            code_hash = hashlib.sha256(python_code.encode("utf-8")).hexdigest()
            param_hash = hashlib.sha256(json.dumps(spec.parameter_ranges, sort_keys=True).encode("utf-8")).hexdigest()
            spec.code_hash = code_hash

            # Persist version in DB
            strat_model = StrategyVersionModel(
                version_id=f"{strategy_id}_{version}",
                strategy_id=strategy_id,
                parent_version_id=None,
                hypothesis_id=hypothesis.id,
                spec_json=spec.model_dump(mode="json"),
                python_code=python_code,
                code_hash=code_hash,
                param_hash=param_hash,
                status="CODED",
            )
            db.add(strat_model)

            # Update hypothesis status
            hyp_record = db.query(HypothesisModel).filter(HypothesisModel.id == hypothesis.id).first()
            if hyp_record:
                hyp_record.status = HypothesisStatus.CODED.value

            db.commit()
            logger.info(f"StrategyCoderAgent generated code for {strategy_id} ({version}) with hash {code_hash[:8]}")
            return spec, python_code

        except ValidationError as ve:
            db.rollback()
            # Update hypothesis to REJECTED
            hyp_record = db.query(HypothesisModel).filter(HypothesisModel.id == hypothesis.id).first()
            if hyp_record:
                hyp_record.status = HypothesisStatus.REJECTED.value
                hyp_record.rejection_reason = str(ve)
                db.commit()
            logger.warning(f"Hypothesis {hypothesis.id} REJECTED by StrategyValidator: {ve}")
            raise
        except Exception as e:
            db.rollback()
            logger.error(f"Failed to code strategy: {e}")
            raise
        finally:
            if own_session:
                db.close()


strategy_coder_agent = StrategyCoderAgent()
