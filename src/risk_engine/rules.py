"""
Risk Rules & Check Result Definitions.
"""

from __future__ import annotations

from dataclasses import dataclass
from enum import Enum
from typing import Optional


class RiskRuleViolation(str, Enum):
    CIRCUIT_BREAKER_HALTED = "CIRCUIT_BREAKER_HALTED"
    CIRCUIT_BREAKER_PAUSED = "CIRCUIT_BREAKER_PAUSED"
    KILL_SWITCH_ENGAGED = "KILL_SWITCH_ENGAGED"
    DATA_STALE = "DATA_STALE"
    BROKER_HEARTBEAT_TIMEOUT = "BROKER_HEARTBEAT_TIMEOUT"
    DAILY_LOSS_LIMIT_EXCEEDED = "DAILY_LOSS_LIMIT_EXCEEDED"
    PEAK_DRAWDOWN_EXCEEDED = "PEAK_DRAWDOWN_EXCEEDED"
    MAX_DAILY_TRADES_EXCEEDED = "MAX_DAILY_TRADES_EXCEEDED"
    MAX_OPEN_POSITIONS_EXCEEDED = "MAX_OPEN_POSITIONS_EXCEEDED"
    MAX_CORRELATED_EXPOSURE_EXCEEDED = "MAX_CORRELATED_EXPOSURE_EXCEEDED"
    SPREAD_TOO_HIGH = "SPREAD_TOO_HIGH"
    NEWS_BLACKOUT = "NEWS_BLACKOUT"
    DISALLOWED_SESSION = "DISALLOWED_SESSION"
    INSUFFICIENT_MARGIN = "INSUFFICIENT_MARGIN"
    LOT_SIZE_OUT_OF_BOUNDS = "LOT_SIZE_OUT_OF_BOUNDS"
    DUPLICATE_IDEMPOTENCY_KEY = "DUPLICATE_IDEMPOTENCY_KEY"
    UNAUTHORIZED_LIVE_ORDER = "UNAUTHORIZED_LIVE_ORDER"


@dataclass
class RiskGateCheckResult:
    approved: bool
    violation: Optional[RiskRuleViolation] = None
    reason: str = "Passed all deterministic risk barriers."
    approved_lots: float = 0.0
